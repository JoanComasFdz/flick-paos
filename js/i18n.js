export const LANGS = ["es", "ca"];
const KEY = "flickpaos:lang";

let lang = readLang();

function readLang() {
  try {
    const saved = localStorage.getItem(KEY);
    if (LANGS.includes(saved)) return saved;
  } catch { /* storage unavailable */ }
  return "es";
}

export function getLang() {
  return lang;
}

export function setLang(next) {
  if (!LANGS.includes(next)) return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* storage unavailable */ }
}

/** BCP 47 locale for dates and relative times. */
export function locale() {
  return lang === "ca" ? "ca-ES" : "es-ES";
}

/** The text for `key` in the current language, with {name} placeholders filled in. */
export function t(key, params = {}) {
  const text = STRINGS[lang][key] ?? STRINGS.es[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in params ? String(params[name]) : `{${name}}`));
}
